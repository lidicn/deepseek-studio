#!/usr/bin/env tsx
/**
 * tools/audit/acl-contract-guard.ts — generate_handler! ↔ capabilities ACL 一致性守卫（20261106）
 *
 * 背景：v0.14.8 P0 —— `studio_request_grant` 注册进了 generate_handler![] 但未进
 * capabilities/default.json 的 permissions → ACL 拒绝 → 页面取券抛错 → agent 通道全死
 * （比 0.14.7 更安静：accepted=0/rejected=0，连重试都没有）。同类：`studio_open_mcp_settings`
 * 同样缺 ACL。根因：ACL 只由真实 Tauri runtime 强制，mock-invoke 测试与 cargo test 都不校验。
 *
 * 判据（正向 only）：
 *   main.rs 里 generate_handler![] 注册的每条命令（去 module:: 前缀、_→- kebab），
 *   必须在 src-tauri/capabilities/*.json 的 permissions 数组里有对应 `allow-<kebab>` 条目。
 *   一条 → FAIL exit 1，点名命令名 + 期望的 permission identifier。
 *
 * 映射规则（从现有 6 条反推）：
 *   open_workbench → allow-open-workbench
 *   updater::updater_check → allow-updater-check（去 module:: 前缀，_→-）
 *   studio_request_grant → allow-studio-request-grant
 *
 * 先红后绿：当前树红 2 条（studio_open_mcp_settings + studio_request_grant）；
 *   Core 加 ACL 后转绿。
 *
 * 用法（gate 阻塞级）：npx tsx tools/audit/acl-contract-guard.ts
 * 可选 --root <path>：扫指定仓根（负控测试用临时仓）。
 */
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const ri = argv.indexOf('--root');
const root = (ri !== -1 && argv[ri + 1]) ? resolve(argv[ri + 1]) : resolve(__dirname, '..', '..');

interface CommandEntry { name: string; expectedPerm: string; line: number }

/** 命令名（去 module:: 前缀）→ allow-<kebab>。 */
function toPermissionId(rawName: string): string {
  const cmdName = rawName.includes('::') ? rawName.split('::').pop()! : rawName;
  return 'allow-' + cmdName.replace(/_/g, '-');
}

/** 从 main.rs 提取 generate_handler![] 里注册的命令。 */
function extractHandlerCommands(filePath: string): CommandEntry[] {
  const src = readFileSync(filePath, 'utf8');
  const lines = src.split('\n');
  const entries: CommandEntry[] = [];
  const re = /generate_handler!\s*\[/;
  for (let i = 0; i < lines.length; i++) {
    if (!re.test(lines[i])) continue;
    // 从下一行开始扫命令，直到遇到 ] 结束
    for (let j = i + 1; j < lines.length; j++) {
      const trimmed = lines[j].trim();
      if (trimmed.includes(']')) break; // 块结束
      if (trimmed.startsWith('//') || !trimmed) continue;
      // 提取标识符（允许 module::func 形态），去尾逗号
      const idMatch = trimmed.match(/^([a-zA-Z_][\w:]*)\s*,?\s*$/);
      if (idMatch) {
        const raw = idMatch[1];
        entries.push({ name: raw.includes('::') ? raw.split('::').pop()! : raw, expectedPerm: toPermissionId(raw), line: j + 1 });
      }
    }
  }
  return entries;
}

/** 从 capabilities/*.json 收集 permissions 数组的全量条目。 */
function extractCapabilitiesPerms(capabilitiesDir: string): Set<string> {
  const set = new Set<string>();
  if (!existsSync(capabilitiesDir)) return set;
  for (const f of readdirSync(capabilitiesDir)) {
    if (!f.endsWith('.json')) continue;
    const conf = JSON.parse(readFileSync(join(capabilitiesDir, f), 'utf8'));
    const perms = conf?.permissions;
    if (Array.isArray(perms)) for (const p of perms) if (typeof p === 'string') set.add(p);
  }
  return set;
}

function main(): void {
  const mainRsPath = join(root, 'src-tauri', 'src', 'main.rs');
  const capabilitiesDir = join(root, 'src-tauri', 'capabilities');

  // 装置自检：防路径写错导致永远绿
  if (!existsSync(mainRsPath)) { console.error('[acl-contract-guard] ERROR: main.rs 不存在: ' + mainRsPath); process.exit(1); }
  const commands = extractHandlerCommands(mainRsPath);
  if (commands.length === 0) {
    console.error('[acl-contract-guard] ERROR: 从 main.rs 提取 generate_handler! 命令 = 0 条，可能解析逻辑或路径变了，请核。');
    process.exit(1);
  }
  // 装置自检：必含已知已放行项 open_workbench（若它不在，说明解析跑偏）
  const knownAllowed = 'allow-open-workbench';
  const cmdNames = commands.map((c) => c.name);
  if (!cmdNames.includes('open_workbench')) {
    console.error(`[acl-contract-guard] ERROR: 提取出的命令里不含已知项 'open_workbench'（解析可能跑偏），实际提取：${cmdNames.join(', ')}。请核。`);
    process.exit(1);
  }

  const perms = extractCapabilitiesPerms(capabilitiesDir);
  if (perms.size === 0) {
    console.error('[acl-contract-guard] ERROR: capabilities/*.json permissions 解析出 0 条，可能 JSON 结构变了，请核。');
    process.exit(1);
  }
  if (!perms.has(knownAllowed)) {
    console.error(`[acl-contract-guard] ERROR: permissions 里不含已知项 '${knownAllowed}'（解析可能跑偏），实际条目数=${perms.size}。请核。`);
    process.exit(1);
  }

  const missing: CommandEntry[] = [];
  for (const c of commands) {
    if (!perms.has(c.expectedPerm)) missing.push(c);
  }

  // ── Check B：每个 allow-* permission 必须有对应 autogenerated toml ──
  // 映射：allow-open-workbench → open_workbench.toml（去 allow- 前缀、kebab→snake）
  const tomlDir = join(root, 'src-tauri', 'permissions', 'autogenerated');
  const missingToml: string[] = [];
  // toml 目录不存在 ⇒ 该仓未构建过，B 无法判定、真跳过（不报 ERROR、不计红）
  if (existsSync(tomlDir)) {
    for (const p of perms) {
      if (!p.startsWith('allow-')) continue; // 跳过 core:* 等
      const tomlName = p.slice(6).replace(/-/g, '_') + '.toml';
      if (!existsSync(join(tomlDir, tomlName))) missingToml.push(`${p} → 缺 ${tomlName}`);
    }
  }

  // ── Check C：mcp-settings 不得出现在任何 capability 的 windows 数组 ──
  // 该窗故意零 Tauri 权限（External URL + HTTP Bearer + init script 删 __TAURI_INTERNALS__）。
  // 加进 windows 是假意图声明（该窗靠 origin 不匹配天然零命令，tauri-2.12.2 authority.rs）——
  // 会让后来人误以为该窗能 invoke，实际不能。
  const bannedWindow = 'mcp-settings';
  const windowViolations: string[] = [];
  if (existsSync(capabilitiesDir)) {
    for (const f of readdirSync(capabilitiesDir)) {
      if (!f.endsWith('.json')) continue;
      const conf = JSON.parse(readFileSync(join(capabilitiesDir, f), 'utf8'));
      const windows: string[] = conf?.windows ?? [];
      if (windows.includes(bannedWindow)) windowViolations.push(`${f}: windows 含 '${bannedWindow}'`);
    }
  }

  // ── 汇总 ──
  const hasFail = missing.length > 0 || missingToml.length > 0 || windowViolations.length > 0;
  if (missing.length > 0) {
    console.error(`[acl-contract-guard] FAIL A: ${missing.length} 条命令未在 capabilities permissions 中放行：`);
    for (const m of missing) console.error(`  main.rs:${m.line}  命令 '${m.name}'  →  缺 '${m.expectedPerm}'`);
  }
  if (missingToml.length > 0) {
    console.error(`[acl-contract-guard] FAIL B: ${missingToml.length} 条 allow-* permission 缺对应 autogenerated toml（可能是忘了重新构建）：`);
    for (const t of missingToml) console.error(`  ${t}`);
  }
  if (windowViolations.length > 0) {
    console.error(`[acl-contract-guard] FAIL C: '${bannedWindow}' 出现在 windows 数组（该窗故意零权限，加进 windows 是开权限）：`);
    for (const v of windowViolations) console.error(`  ${v}`);
  }
  if (hasFail) {
    console.error('[acl-contract-guard] 修复：A 加 allow-<kebab>；B 重新 cargo check 生成 toml；C 从 windows 删除 mcp-settings。');
    process.exit(1);
  }
  console.log(`[acl-contract-guard] PASS — A: ${commands.length} 命令全放行 / B: toml 对应齐全 / C: mcp-settings 不在 windows`);
}

main();
