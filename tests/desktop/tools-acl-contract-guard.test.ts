/**
 * tests/desktop/tools-acl-contract-guard.test.ts — acl-contract-guard 正负控回归。
 *
 * 判据：main.rs generate_handler![] 每条命令（去 module:: 前缀、_→- kebab）必须
 * 在 capabilities/*.json 的 permissions 里有对应 allow-<kebab> 条目。
 *
 * 先红后绿：当前树红 2 条（studio_open_mcp_settings main.rs:1756 + studio_request_grant :1757）；
 * Core 加 ACL 后转绿。本仓用例状态自适应（红/绿都合法，但两态都不得报装置错误）。
 */
import { describe, it, expect, afterAll } from 'vitest';
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const SCRIPT = path.join(ROOT, 'tools', 'audit', 'acl-contract-guard.ts');

function runGuard(rootPath: string): { code: number; output: string } {
  try {
    const stdout = execSync(`npx tsx "${SCRIPT}" --root "${rootPath}"`, {
      cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'],
    });
    return { code: 0, output: stdout };
  } catch (err) {
    const e = err as { status?: number; stdout?: string; stderr?: string };
    return { code: e.status ?? -1, output: `${e.stdout ?? ''}${e.stderr ?? ''}` };
  }
}

function makeTempRepo(commands: string[], perms: string[], tomls?: string[]): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'acl-repo-'));
  fs.mkdirSync(path.join(dir, 'src-tauri', 'src'), { recursive: true });
  fs.mkdirSync(path.join(dir, 'src-tauri', 'capabilities'), { recursive: true });
  fs.mkdirSync(path.join(dir, 'src-tauri', 'permissions', 'autogenerated'), { recursive: true });
  const cmdLines = commands.map((c) => `  ${c},`).join('\n');
  fs.writeFileSync(path.join(dir, 'src-tauri', 'src', 'main.rs'),
    `fn main() {\n  tauri::generate_handler![\n${cmdLines}\n  ]\n}\n`);
  fs.writeFileSync(path.join(dir, 'src-tauri', 'capabilities', 'default.json'),
    JSON.stringify({ permissions: perms, windows: ['main', 'workbench'] }));
  // 可选：放 toml 文件（B 检查需要）
  if (tomls) {
    for (const t of tomls) {
      fs.writeFileSync(path.join(dir, 'src-tauri', 'permissions', 'autogenerated', t),
        `# Automatically generated\n[[permission]]\nidentifier = "allow-${t.replace('.toml', '').replace(/_/g, '-')}"\ncommands.allow = ["${t.replace('.toml', '')}"]\n`);
    }
  }
  return dir;
}

describe('tools/audit/acl-contract-guard', () => {
  const scratch: string[] = [];
  afterAll(() => { for (const p of scratch) { try { fs.rmSync(p, { recursive: true, force: true }); } catch { /* ignore */ } } });

  it('本仓：守卫可运行且产出一致（当前红：点名 2 条；Core 加 ACL 后转绿）', () => {
    const r = runGuard(ROOT);
    expect([0, 1]).toContain(r.code);
    expect(r.output).not.toContain('ERROR');
    if (r.code === 1) {
      expect(r.output).toContain('FAIL A: 2 条');
      expect(r.output).toContain('studio_open_mcp_settings');
      expect(r.output).toContain('studio_request_grant');
    } else {
      expect(r.output).toContain('PASS');
    }
  });

  it('绿：全部命令都有对应 permission → exit 0', () => {
    const dir = makeTempRepo(
      ['open_workbench', 'studio_request_grant'],
      ['core:default', 'allow-open-workbench', 'allow-studio-request-grant'],
      ['open_workbench.toml', 'studio_request_grant.toml'],
    );
    scratch.push(dir);
    const r = runGuard(dir);
    expect(r.code, `应 exit 0，实际输出：${r.output}`).toBe(0);
    expect(r.output).toContain('PASS');
  });

  it('负控：缺一条 permission → exit 1 + 点名命令与期望 permission', () => {
    const dir = makeTempRepo(
      ['open_workbench', 'studio_request_grant'],
      ['core:default', 'allow-open-workbench'], // 缺 allow-studio-request-grant
      ['open_workbench.toml', 'studio_request_grant.toml'], // toml 齐全，只 A 红
    );
    scratch.push(dir);
    const r = runGuard(dir);
    expect(r.code, `负控应 exit 1，实际输出：${r.output}`).toBe(1);
    expect(r.output).toContain('FAIL A: 1 条');
    expect(r.output).toContain('studio_request_grant');
    expect(r.output).toContain('allow-studio-request-grant');
  });

  it('映射规则：module::command 形态去前缀 + _→-', () => {
    // updater::updater_check → allow-updater-check
    const dir = makeTempRepo(
      ['open_workbench', 'updater::updater_check'],
      ['core:default', 'allow-open-workbench', 'allow-updater-check'],
      ['open_workbench.toml', 'updater_check.toml'],
    );
    scratch.push(dir);
    const r = runGuard(dir);
    expect(r.code, `映射测试应 exit 0，实际输出：${r.output}`).toBe(0);
  });

  it('装置自检：提取 0 条命令 → exit 1 + 报解析异常', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'acl-empty-'));
    scratch.push(dir);
    fs.mkdirSync(path.join(dir, 'src-tauri', 'src'), { recursive: true });
    fs.mkdirSync(path.join(dir, 'src-tauri', 'capabilities'), { recursive: true });
    fs.writeFileSync(path.join(dir, 'src-tauri', 'src', 'main.rs'), 'fn main() {}');
    fs.writeFileSync(path.join(dir, 'src-tauri', 'capabilities', 'default.json'), '{"permissions":["core:default","allow-open-workbench"],"windows":["main"]}');
    const r = runGuard(dir);
    expect(r.code).toBe(1);
    expect(r.output).toContain('0 条');
  });

  it('Check B 负控：allow-* 缺对应 toml → exit 1 + 点名', () => {
    const dir = makeTempRepo(
      ['open_workbench', 'studio_request_grant'],
      ['core:default', 'allow-open-workbench', 'allow-studio-request-grant'],
      ['open_workbench.toml'], // 故意缺 studio_request_grant.toml
    );
    scratch.push(dir);
    const r = runGuard(dir);
    expect(r.code).toBe(1);
    expect(r.output).toContain('FAIL B');
    expect(r.output).toContain('allow-studio-request-grant');
    expect(r.output).toContain('studio_request_grant.toml');
  });

  it('Check C 负控：mcp-settings 出现在 windows → exit 1', () => {
    const dir = makeTempRepo(
      ['open_workbench'],
      ['core:default', 'allow-open-workbench'],
      ['open_workbench.toml'],
    );
    // 在 capabilities 里加 mcp-settings 到 windows
    const capPath = path.join(dir, 'src-tauri', 'capabilities', 'default.json');
    const cap = JSON.parse(fs.readFileSync(capPath, 'utf8'));
    cap.windows.push('mcp-settings');
    fs.writeFileSync(capPath, JSON.stringify(cap));
    const r = runGuard(dir);
    expect(r.code).toBe(1);
    expect(r.output).toContain('FAIL C');
    expect(r.output).toContain('mcp-settings');
  });
});
